def slugify(name: str) -> str:
    import re
    s = name.lower().strip()
    s = re.sub(r"[\s\.\-]+", " ", s)
    s = re.sub(r"[^a-z0-9]+", "_", s)
    return s.strip("_").lower()

def main():
    out = Path(__file__).resolve().parent.parent / "backend" / "data" / "esco_skills_min.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    seen = set()
    rows = []
    for cat, name, aliases in iter_entries():
        slug = slugify(name)
        if slug in seen:
            continue
        seen.add(slug)
        all_aliases = [slug] + [slugify(a) for a in aliases] + [name.lower()]
        all_aliases = [a for a in all_aliases if a]
        unique = list(dict.fromkeys(all_aliases))
        rows.append([slug, name, cat, ";".join(unique)])
    with open(out, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["id", "skill", "category", "aliases"])
        w.writerows(rows)
    print(f"wrote {len(rows)} rows to {out}")

if __name__ == "__main__":
    main()
